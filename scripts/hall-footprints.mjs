// Measures every hall's footing from its art and writes src/data/hallfoot.js.
//   node scripts/hall-footprints.mjs          (rerun after a hall's art changes)
// A hall's footing is an ellipse on the ground round its anchor (t.x, t.y):
// half as wide as the widest of its nine forms at ground level (everything
// drawn from 4 units above the anchor down: the base, the steps, the props
// standing beside it), reaching down to its lowest pixel and up a little
// behind (TOP_K of the half-width). The widest form, so an upgrade never
// grows into a neighbour; mirrored, so a hall that turns keeps its room.
import fs from "node:fs";
const ROOT = new URL("..", import.meta.url).pathname.replace(/\/$/, "");
const kit = await import(ROOT + "/src/render/pix/hall-kit.js");
const KINDS = ["archer", "knight", "wizard", "spiker", "catapult", "support", "trapsmith", "goldworks", "riverwatch", "falconry", "assassin", "gunpowder", "sunforge", "band"];
const FORMS = ["1", "2", "3", "a", "aa", "ab", "b", "ba", "bb"];
const GROUND = -8;     // art px (4 board units) above the anchor: what is drawn below this stands on the ground
const TOP_K = 0.5;     // how far the footing reaches up behind the anchor, of its half-width (a little room so a hall behind still shows its door)
const formOf = (f) => (/^\d$/.test(f) ? { level: Number(f), branch: null, rank4: null } : { level: 3, branch: f[0], rank4: f[1] || null });
const out = {};
for (const k of KINDS) {
  const mod = await import(`${ROOT}/src/render/pix/hall-${k}.js`);
  let hw = 0, bot = 0;
  for (const f of FORMS) for (const seed of [0, 1, 2]) {
    const img = kit.bakeHall(mod.BOX, mod.build({ ...formOf(f), seed, style: "B" }), {}).back;
    for (let j = 0; j < img.h; j++) for (let i = 0; i < img.w; i++) {
      if (img.data[(j * img.w + i) * 4 + 3] < 128) continue;
      const x = i - img.ox, y = j - img.oy;
      if (y < GROUND) continue;
      hw = Math.max(hw, Math.abs(x + 0.5)); bot = Math.max(bot, y + 1);
    }
  }
  const rx = Math.round(hw / 2), down = Math.round(bot / 2), up = Math.round(rx * TOP_K);
  out[k] = { rx, up, down };
  console.log(k.padEnd(11), out[k]);
}
const body = Object.entries(out).map(([k, v]) => `  ${k}: { rx: ${v.rx}, up: ${v.up}, down: ${v.down} },`).join("\n");
fs.writeFileSync(ROOT + "/src/data/hallfoot.js", `// GENERATED by scripts/hall-footprints.mjs from the halls' art: rerun it after a hall's
// art changes. Each hall's footing on the ground, in board units round its anchor:
// rx = half its width, up = how far it reaches behind (up the screen), down = in front.
// Read through engine/footing.js; see its header for the rules.
export const HALL_FOOT = {
${body}
};
`);
